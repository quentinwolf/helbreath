// Command magicimport parses Helbreath Magic.cfg and generates Go source
// code containing spell definitions for the magic package.
//
// Usage:
//
//	go run ./server/tools/magicimport/ [-cfg path/to/Magic.cfg] [-ts client/src/constants/SpellCosts.ts] > server/internal/magic/spelldefs_gen.go
//
// Run gofmt on the output. -ts also writes the client's spell price table.
//
// The v3.82 Magic.cfg ships in the Equilibrium server files
// (github.com/play-helbreath/helbreath-equilibrium, server/Core/Magic.cfg).
// Spell behaviour follows the original server's DEF_MAGICTYPE_* handling.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// rawSpell holds all fields parsed from a single "magic = " line.
//
// Format from Magic.cfg header:
//
//	magic = Num Name Type Delay Last Mana Range1 Range2
//	        Effect1 Effect2 Effect3  Effect4 Effect5 Effect6  Effect7 Effect8 Effect9
//	        Int Cost Cat Attr
type rawSpell struct {
	ID   int
	Name string // with hyphens replaced by spaces

	CfgType int // original Type field from cfg
	Delay   int // cooldown in seconds (0 = instant)
	Last    int // duration in seconds
	Mana    int // mana cost

	Range1 int // range value 1
	Range2 int // range value 2

	// Three groups of three effect values each
	Eff1, Eff2, Eff3 int // effect group 1 (dice throws, dice range, bonus)
	Eff4, Eff5, Eff6 int // effect group 2
	Eff7, Eff8, Eff9 int // effect group 3

	ReqINT int // required INT/MAG stat
	Cost   int // gold cost to learn (-1 = not purchasable)
	Cat    int // category (0=none, 1=offensive, 2=defensive)
	Attr   int // attribute/element (0=none, 1=earth, 2=light, 3=fire, 4=ice)
}

func main() {
	cfgPath := flag.String("cfg", "", "path to Magic.cfg (default: <repo>/helbreath-v3.82-master/Server/Core/Magic.cfg)")
	tsOut := flag.String("ts", "", "also write the client's spell price table here (client/src/constants/SpellCosts.ts)")
	flag.Parse()

	path := *cfgPath
	if path == "" {
		repoRoot := os.Getenv("REPO_ROOT")
		if repoRoot == "" {
			cwd, _ := os.Getwd()
			repoRoot = findRepoRoot(cwd)
			if repoRoot == "" {
				log.Fatal("Cannot determine repo root. Set REPO_ROOT env variable or pass -cfg.")
			}
		}
		path = filepath.Join(repoRoot, "helbreath-v3.82-master/Server/Core/Magic.cfg")
	}
	spells, err := parseCfgFile(path)
	if err != nil {
		log.Fatalf("parsing %s: %v", path, err)
	}

	sort.Slice(spells, func(i, j int) bool { return spells[i].ID < spells[j].ID })

	fmt.Fprintf(os.Stderr, "Parsed %d spells from Magic.cfg\n", len(spells))

	generate(spells)
	if *tsOut != "" {
		if err := writeCostsTS(*tsOut, spells); err != nil {
			log.Fatalf("writing %s: %v", *tsOut, err)
		}
	}
}

// writeCostsTS writes every spell's gold price for the client's Learn tab. The
// spell catalog message has no price field, and this keeps both sides on the
// same Magic.cfg.
func writeCostsTS(path string, spells []rawSpell) error {
	var b strings.Builder
	b.WriteString("// Code generated by server/tools/magicimport -ts; DO NOT EDIT.\n")
	b.WriteString("// Gold Gandalf charges to learn each spell (Magic.cfg Cost column), by spell ID.\n")
	b.WriteString("// -1 = not sold, only learnt from a manual (GMs can still learn it).\n")
	b.WriteString("export const SPELL_GOLD_COST: Record<number, number> = {\n")
	for _, s := range spells {
		fmt.Fprintf(&b, "  %d: %d, // %s\n", s.ID, s.Cost, cleanName(s.Name))
	}
	b.WriteString("};\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func findRepoRoot(dir string) string {
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return ""
		}
		dir = parent
	}
}

func parseCfgFile(path string) ([]rawSpell, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	var spells []rawSpell
	scanner := bufio.NewScanner(f)
	scanner.Buffer(make([]byte, 1024*1024), 1024*1024)

	for scanner.Scan() {
		line := scanner.Text()
		trimmed := strings.TrimSpace(line)
		if trimmed == "" || strings.HasPrefix(trimmed, "//") || strings.HasPrefix(trimmed, "[") {
			continue
		}

		if !strings.HasPrefix(trimmed, "magic") {
			continue
		}

		spell, err := parseMagicLine(trimmed)
		if err != nil {
			fmt.Fprintf(os.Stderr, "WARN: skipping: %v: %q\n", err, trimmed)
			continue
		}
		if strings.HasPrefix(spell.Name, "Test-Spell") {
			continue // developer placeholders in the original file, never learnable
		}
		spells = append(spells, spell)
	}

	return spells, scanner.Err()
}

func parseMagicLine(line string) (rawSpell, error) {
	rest := strings.TrimPrefix(line, "magic")
	rest = strings.TrimSpace(rest)
	if len(rest) == 0 || rest[0] != '=' {
		return rawSpell{}, fmt.Errorf("missing '=' after magic")
	}
	rest = rest[1:]
	rest = strings.TrimSpace(rest)

	fields := strings.Fields(rest)
	// ID + Name + 19 numeric fields = 21 minimum
	// Fields: Type Delay Last Mana Range1 Range2 Eff1..Eff9 Int Cost Cat Attr
	if len(fields) < 21 {
		return rawSpell{}, fmt.Errorf("expected >=21 fields, got %d", len(fields))
	}

	id, err := atoi(fields[0])
	if err != nil {
		return rawSpell{}, fmt.Errorf("bad ID %q: %w", fields[0], err)
	}
	name := fields[1]

	nums := make([]int, 0, 19)
	for i := 2; i < len(fields) && len(nums) < 19; i++ {
		n, err := atoi(fields[i])
		if err != nil {
			return rawSpell{}, fmt.Errorf("field[%d] %q: %w", i, fields[i], err)
		}
		nums = append(nums, n)
	}

	if len(nums) < 19 {
		return rawSpell{}, fmt.Errorf("expected 19 numeric fields, got %d", len(nums))
	}

	return rawSpell{
		ID:      id,
		Name:    name,
		CfgType: nums[0],  // Type
		Delay:   nums[1],  // Delay
		Last:    nums[2],  // Last (duration)
		Mana:    nums[3],  // Mana
		Range1:  nums[4],  // Range1
		Range2:  nums[5],  // Range2
		Eff1:    nums[6],  // Effect group 1
		Eff2:    nums[7],
		Eff3:    nums[8],
		Eff4:    nums[9],  // Effect group 2
		Eff5:    nums[10],
		Eff6:    nums[11],
		Eff7:    nums[12], // Effect group 3
		Eff8:    nums[13],
		Eff9:    nums[14],
		ReqINT:  nums[15], // Int requirement
		Cost:    nums[16], // Gold cost
		Cat:     nums[17], // Category
		Attr:    nums[18], // Attribute/Element
	}, nil
}

func atoi(s string) (int, error) {
	return strconv.Atoi(strings.TrimSpace(s))
}

