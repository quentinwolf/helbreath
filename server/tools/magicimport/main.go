// dice is one Magic.cfg effect group: count, sides, bonus.
type dice struct{ count, sides, bonus int }

func (d dice) zero() bool { return d.count <= 0 && d.bonus <= 0 }

func (d dice) min() int {
	if d.sides <= 0 {
		return d.bonus
	}
	return d.count + d.bonus
}

func (d dice) max() int {
	if d.sides <= 0 {
		return d.bonus
	}
	return d.count*d.sides + d.bonus
}

func (d dice) goLiteral() string {
	return fmt.Sprintf("Dice{Count: %d, Sides: %d, Bonus: %d}", d.count, d.sides, d.bonus)
}

// hitPattern is where a damage spell lands, following the original server's
// switch on DEF_MAGICTYPE_* in its magic handler. Range1/Range2 (the cfg's
// "range23", sValue2/3) are the half-size of the box around the clicked tile;
// effect groups 1 and 2 are sValue4-6 and sValue7-9.
type hitPattern struct {
	areaX, areaY int
	line         bool
	centre       dice // extra on the clicked tile
	area         dice // everyone in the box
	lineDice     dice // everyone on the line from the caster
}

func (h hitPattern) damages() bool {
	return !h.centre.zero() || !h.area.zero() || !h.lineDice.zero()
}

func spellHitPattern(s rawSpell) hitPattern {
	g1 := dice{s.Eff1, s.Eff2, s.Eff3}
	g2 := dice{s.Eff4, s.Eff5, s.Eff6}
	box := hitPattern{areaX: s.Range1, areaY: s.Range2}

	switch s.CfgType {
	case 1, 24: // DAMAGE_SPOT, DAMAGE_SPOT_RANDOM: whoever is on the tile
		return hitPattern{centre: g1}
	case 3: // DAMAGE_AREA: tile gets g1, box gets g2
		box.centre, box.area = g1, g2
	case 21, 22, 28: // DAMAGE_AREA_NOSPOT, TREMOR, DAMAGE_AREA_ARMOR_BREAK: box only, g2
		box.area = g2
	case 23, 25, 52: // ICE (also freezes, g3 count = seconds), DAMAGE_AREA_NOSPOT_SPDOWN, EXPLOSION: box only, g1
		box.area = g1
	case 19, 26: // DAMAGE_LINEAR, ICE_LINEAR: line and box get g2, tile gets g1
		box.line, box.centre, box.area, box.lineDice = true, g1, g2, g2
	case 30: // DAMAGE_LINEAR_SPDOWN: box gets g1, line gets g2
		box.line, box.area, box.lineDice = true, g1, g2
	case 14: // CREATE_DYNAMIC (Fire Wall, Spike Field, clouds): no hit on cast; the
		// field it leaves does the damage (SpellDef.Field). g3 is the field's
		// kind/layout/size, not dice.
		return hitPattern{}
	default:
		return hitPattern{}
	}
	return box
}

// fieldKindName is the magic.FieldKind constant for a DEF_DYNAMICOBJECT_* number.
func fieldKindName(kind int) string {
	switch kind {
	case 1:
		return "FieldFire"
	case 8:
		return "FieldIceStorm"
	case 9:
		return "FieldSpike"
	case 10:
		return "FieldPoisonCloud"
	}
	return fmt.Sprintf("FieldKind(%d)", kind)
}

// fieldLayoutName is the magic.FieldLayout constant for Magic.cfg sValue11.
func fieldLayoutName(layout int) string {
	switch layout {
	case 1:
		return "FieldWall"
	case 2:
		return "FieldSquare"
	}
	return "FieldSingle"
}

// mapSpellType converts the original Helbreath CfgType to our SpellType string.
func mapSpellType(s rawSpell) string {
	if h := spellHitPattern(s); h.damages() {
		if h.line || h.areaX > 0 || h.areaY > 0 {
			return "SpellTypeAOE"
		}
		return "SpellTypeDamage"
	}

	switch s.CfgType {
	case 14: // CREATE_DYNAMIC: a lasting damage field
		return "SpellTypeAOE"
	case 5: // SPDOWN_AREA (Staminar Drain): drains stamina, no damage
		return "SpellTypeDebuff"

	// Heal spells
	case 2: // Heal, Great Heal, Critical Heal, Regenerate
		return "SpellTypeHeal"
	case 27: // Mass Heal
		return "SpellTypeHeal"

	// Buff spells
	case 11: // Defense Shield, Protection From Arrow, Protection From Magic, etc.
		return "SpellTypeBuff"
	case 51: // Mantles (Wood, Bloody, Magic)
		return "SpellTypeBuff"
	case 60: // Warrior Spirit
		return "SpellTypeBuff"

	// Debuff spells
	case 12: // Hold Person, Paralyze, Entangle, Medusa Kiss
		return "SpellTypeDebuff"
	case 15: // Possession
		return "SpellTypeDebuff"
	case 16: // Confuse Language, Confusion, Illusion, etc.
		return "SpellTypeDebuff"
	case 17: // Poison, Cure (Cure is special, but categorize under debuff for now)
		if s.Eff1 == 0 && s.Eff2 == 0 && s.Eff3 == 0 {
			return "SpellTypeHeal" // Cure removes poison
		}
		return "SpellTypeDebuff"
	case 28: // Armor Break
		return "SpellTypeDebuff"
	case 29: // Cancellation
		return "SpellTypeDebuff"
	case 31: // Inhibition Casting
		return "SpellTypeDebuff"
	case 50: // Magic Drain
		return "SpellTypeDebuff"

	// Summon
	case 9: // Summon Creature
		return "SpellTypeSummon"

	// Teleport
	case 8: // Recall
		return "SpellTypeTeleport"

	// Special/utility
	case 10: // Create Food
		return "SpellTypeBuff"
	case 13: // Invisibility, Detect Invisibility
		return "SpellTypeBuff"
	case 18: // Peace, Prayer, Berserk, Trance
		return "SpellTypeBuff"
	case 20: // Polymorph
		return "SpellTypeBuff"
	case 32: // Resurrection
		return "SpellTypeHeal"
	case 33: // Scan
		return "SpellTypeBuff"

	// Stamina recovery
	case 7: // Staminar Recovery, Great Staminar Recovery, Mass Staminar Recovery
		return "SpellTypeHeal"

	default:
		return "SpellTypeDamage" // fallback
	}
}

// mapElement converts the Attr field to our element constant.
// Original: 0=none, 1=earth, 2=light/lightning, 3=fire, 4=ice
func mapElement(attr int) string {
	switch attr {
	case 1:
		return "ElementEarth"
	case 2:
		return "ElementLight"
	case 3:
		return "ElementFire"
	case 4:
		return "ElementIce"
	default:
		return "ElementNone"
	}
}

// mapApplyEffect determines which status effect a spell should apply.
func mapApplyEffect(s rawSpell) (effectName string, level int) {
	switch s.CfgType {
	case 23: // ICE: freezes whoever it hits (for Eff7 seconds, see calcDuration)
		return "EffectIce", 1
	case 12: // Hold/Paralyze/Entangle/Medusa
		level = s.Eff1
		if level <= 0 {
			level = 1
		}
		return "EffectHold", level // 1 = Hold Person, 2 = Paralyze: can't move
	case 13: // Eff1 (the original's sValue4): 1 = Invisibility, 2 = Detect Invisibility
		if s.Eff1 == 1 {
			return "EffectInvisibility", 1
		}
		return "", 0
	case 16: // Confusion/Illusion
		level = s.Eff1
		if level <= 0 {
			level = 1
		}
		return "EffectConfusion", level
	case 17: // Poison (only if applying poison, not cure)
		if s.Eff1 > 0 && s.Eff2 > 0 {
			return "EffectPoison", 1
		}
		return "", 0
	case 11: // PROTECT: Eff1 picks the kind, as in the original server
		switch s.Eff1 {
		case 2: // Protection From Magic
			return "EffectMagicProtection", 1
		case 3: // Defense Shield
			return "EffectDefenseShield", 1
		case 4: // Great Defense Shield
			return "EffectDefenseShield", 2
		case 5: // Absolute Magic Protection
			return "EffectMagicProtection", 3
		}
		return "", 0 // 1 = Protection From Arrow: no arrow protection effect yet
	case 18: // Berserk/Trance/Prayer
		nameUp := strings.ToUpper(s.Name)
		if strings.Contains(nameUp, "BERSERK") {
			return "EffectBerserk", 1
		}
		if strings.Contains(nameUp, "TRANCE") {
			return "EffectBerserk", 2
		}
		return "", 0
	case 28: // Armor Break
		return "", 0 // Direct damage effect, not status
	case 29: // Cancellation
		return "", 0
	case 31: // Inhibition Casting
		return "EffectInhibition", s.Eff1
	case 50: // Magic Drain
		return "", 0
	case 51: // Mantles
		return "EffectDefenseShield", s.Eff1
	}
	return "", 0
}

// calcDamage is what the main target can take: the centre roll plus the area
// roll (the clicked tile is inside the box too), or the line roll if there is
// no box damage.
func calcDamage(s rawSpell) (minDmg, maxDmg int) {
	h := spellHitPattern(s)
	if !h.damages() {
		return 0, 0
	}
	other := h.area
	if other.zero() {
		other = h.lineDice
	}
	return h.centre.min() + other.min(), h.centre.max() + other.max()
}

// calcHealAmount extracts healing value from the spell.
func calcHealAmount(s rawSpell) int {
	spType := mapSpellType(s)
	if spType != "SpellTypeHeal" {
		return 0
	}

	// For heal spells, effect group 1 is typically: dice_count, dice_range, bonus
	diceCount, diceRange, bonus := s.Eff1, s.Eff2, s.Eff3
	if diceCount <= 0 {
		return 0
	}
	if diceRange <= 0 {
		return diceCount + bonus
	}
	// Average heal = (min + max) / 2; min = count + bonus, max = count*range + bonus
	avg := (diceCount + bonus + diceCount*diceRange + bonus) / 2
	if avg <= 0 {
		avg = diceCount + bonus
	}

	// Add second effect group if present
	if s.Eff4 > 0 && s.Eff5 > 0 {
		avg2 := (s.Eff4 + s.Eff6 + s.Eff4*s.Eff5 + s.Eff6) / 2
		avg += avg2
	}

	return avg
}

// calcRadius is the larger half-size of the damage box (0 = single tile).
func calcRadius(s rawSpell) int {
	h := spellHitPattern(s)
	if !h.damages() {
		return 0
	}
	return max(h.areaX, h.areaY)
}

// screenRange marks spells cast anywhere on screen (magic.MaxCastRange).
const screenRange = -1

// calcRange is the casting range in tiles. Magic.cfg has no cast range: its
// "range" columns are the hit box. Offensive spells reach anything on screen;
// heals and buffs here are self-cast.
func calcRange(s rawSpell) int {
	switch mapSpellType(s) {
	case "SpellTypeHeal", "SpellTypeBuff", "SpellTypeTeleport":
		return 0
	case "SpellTypeSummon":
		return s.Range1
	}
	return screenRange
}

// calcCooldown returns cooldown in ms from the Delay field (seconds).
// calcCooldown is the original Delay column (seconds) when set, e.g.
// Resurrection or the mantles. Otherwise the original had no cooldown beyond
// the cast itself, so a spell can be recast once its cast time has passed.
func calcCooldown(s rawSpell) int {
	if s.Delay > 0 {
		return s.Delay * 1000
	}
	return calcCastTime(s)
}

// calcCastTime returns cast time in ms based on spell tier.
func calcCastTime(s rawSpell) int {
	if s.Mana <= 20 {
		return 500
	}
	if s.Mana <= 40 {
		return 700
	}
	if s.Mana <= 60 {
		return 900
	}
	if s.Mana <= 100 {
		return 1100
	}
	if s.Mana <= 150 {
		return 1300
	}
	return 1500
}

// calcDuration returns duration in seconds from the Last field.
func calcDuration(s rawSpell) int {
	if s.CfgType == 23 && s.Eff7 > 0 {
		return s.Eff7 // ICE: freeze seconds (the original's sValue10)
	}
	if s.Last > 0 {
		return s.Last
	}
	// Some buffs have implicit duration
	spType := mapSpellType(s)
	switch spType {
	case "SpellTypeBuff":
		return 60
	case "SpellTypeDebuff":
		return 30
	}
	return 0
}

// cleanName converts hyphenated name to spaces and handles special chars.
func cleanName(name string) string {
	n := strings.ReplaceAll(name, "-", " ")
	n = strings.ReplaceAll(n, ".", "")
	n = strings.ReplaceAll(n, "'", "'")
	// Fix "s " at beginning from possessives like "Forge s Breath" -> "Forge's Breath"
	n = strings.ReplaceAll(n, " s ", "'s ")
	// The original's "Staminar" (Staminar Drain, Staminar Recovery) is a mistranslation
	n = strings.ReplaceAll(n, "Staminar", "Stamina")
	n = strings.ReplaceAll(n, "Recov", "Recovery")
	n = strings.ReplaceAll(n, "Recoveryery", "Recovery")
	return n
}

