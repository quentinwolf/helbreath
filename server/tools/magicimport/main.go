func generate(spells []rawSpell) {
	p := func(format string, args ...any) {
		fmt.Printf(format, args...)
	}

	p("// Code generated by tools/magicimport; DO NOT EDIT.\n")
	p("//\n")
	p("// Source: Helbreath v3.82 Server/Core/Magic.cfg\n")
	p("// Contains all %d original Helbreath spells, at their original IDs.\n", len(spells))
	p("package magic\n\n")
	p("// init registers every spell parsed from the original Magic.cfg.\n")
	p("func init() {\n")

	for _, s := range spells {
		spType := mapSpellType(s)
		element := mapElement(s.Attr)
		minDmg, maxDmg := calcDamage(s)
		healAmt := calcHealAmount(s)
		radius := calcRadius(s)
		rng := calcRange(s)
		cooldown := calcCooldown(s)
		castTime := calcCastTime(s)
		duration := calcDuration(s)
		effectName, effectLevel := mapApplyEffect(s)

		name := cleanName(s.Name)

		// Tick damage for poison spells
		tickDmg := 0
		tickInterval := 0
		if effectName == "EffectPoison" {
			tickDmg = s.Eff2 // dice range as tick damage
			if tickDmg <= 0 {
				tickDmg = 5
			}
			tickInterval = 3000
		}

		// Buff stats for buff spells
		buffStat := 0
		buffAmount := 0
		if spType == "SpellTypeBuff" {
			switch s.CfgType {
			case 11: // Defense buffs
				// EffectValue is the buff amount
				if s.Eff2 > 0 {
					buffStat = 2 // VIT
					buffAmount = s.Eff2 / 10
					if buffAmount < 1 {
						buffAmount = s.Eff1
					}
				}
			case 18: // Prayer/Berserk
				nameUp := strings.ToUpper(s.Name)
				if strings.Contains(nameUp, "BERSERK") || strings.Contains(nameUp, "TRANCE") {
					buffStat = 1 // STR
					buffAmount = s.Eff1
				} else if strings.Contains(nameUp, "PRAYER") {
					buffStat = 2 // VIT
					buffAmount = s.Eff2
				}
			}
		}

		// Cost to learn: -1 means not purchasable (quest/special)
		learnCost := s.Cost
		if learnCost < 0 {
			learnCost = 0
		}

		// Magic.cfg's only learning requirement is INT ("ReqInt"); the original
		// had no level or MAG requirement for learning.
		reqLevel := 0

		// SpriteID = spell ID (client can map these)
		spriteID := s.ID
		// SoundID based on element
		soundID := 1
		switch s.Attr {
		case 3: // fire
			soundID = 4
		case 4: // ice
			soundID = 46
		case 2: // lightning
			soundID = 5
		case 1: // earth
			soundID = 7
		}
		if spType == "SpellTypeHeal" {
			soundID = 45
		}

		rngExpr := strconv.Itoa(rng)
		if rng == screenRange {
			rngExpr = "MaxCastRange"
		}
		hit := spellHitPattern(s)

		p("\tSpellDB[%d] = &SpellDef{\n", s.ID)
		p("\t\tID: %d, Name: %q, CfgType: %d,\n", s.ID, name, s.CfgType)
		p("\t\tType: %s, Element: %s,\n", spType, element)
		p("\t\tManaCost: %d, CastTime: %d, Cooldown: %d, Range: %s,\n",
			s.Mana, castTime, cooldown, rngExpr)

		if hit.damages() {
			if hit.areaX > 0 || hit.areaY > 0 {
				p("\t\tAreaX: %d, AreaY: %d, Radius: %d,\n", hit.areaX, hit.areaY, radius)
			}
			if hit.line {
				p("\t\tLine: true,\n")
			}
			if !hit.centre.zero() {
				p("\t\tCentreDice: %s,\n", hit.centre.goLiteral())
			}
			if !hit.area.zero() {
				p("\t\tAreaDice: %s,\n", hit.area.goLiteral())
			}
			if !hit.lineDice.zero() {
				p("\t\tLineDice: %s,\n", hit.lineDice.goLiteral())
			}
		}
		if minDmg > 0 || maxDmg > 0 {
			p("\t\tMinDamage: %d, MaxDamage: %d,\n", minDmg, maxDmg)
		}
		if healAmt > 0 {
			p("\t\tHealAmount: %d,\n", healAmt)
		}
		// Heals as the original rolls them: HPUP_SPOT (2) heals whoever is on the
		// clicked tile with group 1; SPUP_AREA (7) and Mass Heal (27) add group 2
		// for everyone in the Range1 x Range2 box around it.
		switch s.CfgType {
		case 2, 7, 27:
			if d := (dice{s.Eff1, s.Eff2, s.Eff3}); !d.zero() {
				p("\t\tHealDice: %s,\n", d.goLiteral())
			}
			if d := (dice{s.Eff4, s.Eff5, s.Eff6}); s.CfgType != 2 && !d.zero() {
				p("\t\tAreaX: %d, AreaY: %d,\n", s.Range1, s.Range2)
				p("\t\tAreaHealDice: %s,\n", d.goLiteral())
			}
		}
		if duration > 0 {
			p("\t\tDuration: %d,\n", duration)
		}
		switch s.CfgType {
		case 16: // CONFUSE: everyone in the Range1 x Range2 box around the tile
			p("\t\tAreaX: %d, AreaY: %d,\n", s.Range1, s.Range2)
		case 5: // SPDOWN_AREA (Staminar Drain): group 1 off the clicked player's
			// stamina, group 2 off everyone in the box (them included)
			p("\t\tAreaX: %d, AreaY: %d,\n", s.Range1, s.Range2)
			p("\t\tSPDice: %s,\n", (dice{s.Eff1, s.Eff2, s.Eff3}).goLiteral())
			p("\t\tAreaSPDice: %s,\n", (dice{s.Eff4, s.Eff5, s.Eff6}).goLiteral())
		}
		if s.CfgType == 14 {
			// sValue10 = DEF_DYNAMICOBJECT_* kind, sValue11 = layout,
			// sValue12 = size, sValue5 = strength (poison level)
			p("\t\tField: FieldSpec{Kind: %s, Layout: %s, Size: %d, Power: %d},\n",
				fieldKindName(s.Eff7), fieldLayoutName(s.Eff8), s.Eff9, s.Eff2)
		}
		if buffStat > 0 {
			p("\t\tBuffStat: %d, BuffAmount: %d,\n", buffStat, buffAmount)
		}
		p("\t\tReqLevel: %d, ReqMAG: 0, ReqINT: %d,\n", reqLevel, s.ReqINT)
		p("\t\tGoldCost: %d,\n", s.Cost)
		p("\t\tSpriteID: %d, SoundID: %d,\n", spriteID, soundID)

		if effectName != "" && effectLevel > 0 {
			p("\t\tApplyEffect: %s, EffectLevel: %d,\n", effectName, effectLevel)
		}
		if tickDmg > 0 {
			p("\t\tTickDamage: %d, TickIntervalMs: %d,\n", tickDmg, tickInterval)
		}

		p("\t}\n\n")
	}

	p("}\n")
}
