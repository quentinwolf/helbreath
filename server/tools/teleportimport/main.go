// Command teleportimport turns the original server's map doors and exits
// (teleport-loc lines in MAPDATA/*.txt) into server/internal/mapdata/teleports_gen.go.
//
//	go run ./server/tools/teleportimport -src "<HelbreathServer-main>/Files/GameServers" \
//	    -maps assets/MAPDATA > server/internal/mapdata/teleports_gen.go
//
// Line format: teleport-loc = <x> <y> <destMap> <destX> <destY> <dir>.
// Only doors whose map and destination both exist in the port (-maps) are
// written, with map names spelled as the port's .amd files.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type door struct {
	src         string
	x, y        int
	dest        string
	dx, dy, dir int
}

func main() {
	src := flag.String("src", "", "original GameServers folder (searched for MAPDATA/*.txt)")
	mapsDir := flag.String("maps", "assets/MAPDATA", "the port's .amd folder")
	flag.Parse()
	if *src == "" {
		log.Fatal("-src is required")
	}

	portMaps := map[string]string{}
	entries, err := os.ReadDir(*mapsDir)
	if err != nil {
		log.Fatal(err)
	}
	for _, e := range entries {
		if strings.EqualFold(filepath.Ext(e.Name()), ".amd") {
			name := strings.TrimSuffix(e.Name(), filepath.Ext(e.Name()))
			portMaps[strings.ToLower(name)] = name
		}
	}

	var doors []door
	missing := map[string]int{}
	seen := map[string]bool{}
	err = filepath.Walk(*src, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || !strings.EqualFold(filepath.Ext(path), ".txt") ||
			!strings.EqualFold(filepath.Base(filepath.Dir(path)), "mapdata") {
			return err
		}
		key := strings.ToLower(strings.TrimSuffix(filepath.Base(path), filepath.Ext(path)))
		srcMap, ok := portMaps[key]
		if !ok || seen[key] {
			return nil
		}
		seen[key] = true
		f, err := os.Open(path)
		if err != nil {
			return err
		}
		defer f.Close()
		sc := bufio.NewScanner(f)
		for sc.Scan() {
			line := strings.TrimSpace(sc.Text())
			if !strings.HasPrefix(strings.ToLower(line), "teleport-loc") {
				continue
			}
			_, rest, ok := strings.Cut(line, "=")
			if !ok {
				continue
			}
			fl := strings.Fields(strings.Split(rest, "//")[0])
			if len(fl) < 6 {
				continue
			}
			n := func(i int) int { v, _ := strconv.Atoi(fl[i]); return v }
			dest, ok := portMaps[strings.ToLower(fl[2])]
			if !ok {
				missing[fl[2]]++
				continue
			}
			doors = append(doors, door{srcMap, n(0), n(1), dest, n(3), n(4), n(5)})
		}
		return sc.Err()
	})
	if err != nil {
		log.Fatal(err)
	}
	sort.SliceStable(doors, func(i, j int) bool {
		a, b := doors[i], doors[j]
		if a.src != b.src {
			return a.src < b.src
		}
		if a.y != b.y {
			return a.y < b.y
		}
		return a.x < b.x
	})

	fmt.Println("// Code generated by tools/teleportimport; DO NOT EDIT.")
	fmt.Println("//")
	fmt.Println("// Source: the original server's MAPDATA/*.txt teleport-loc lines")
	fmt.Println("// (HelbreathServer-main, HB Server Files 3.51 default maps).")
	fmt.Println()
	fmt.Println("package mapdata")
	fmt.Println()
	fmt.Println("// originalTeleports are the original doors and exits: source tile -> destination.")
	fmt.Println("var originalTeleports = []struct {")
	fmt.Println("\tSrc  string")
	fmt.Println("\tX, Y int")
	fmt.Println("\tTeleportDest")
	fmt.Println("}{")
	srcs := map[string]bool{}
	for _, d := range doors {
		srcs[d.src] = true
		fmt.Printf("\t{%q, %d, %d, TeleportDest{DestMap: %q, DestX: %d, DestY: %d, Dir: %d}},\n",
			d.src, d.x, d.y, d.dest, d.dx, d.dy, d.dir)
	}
	fmt.Println("}")
	var names []string
	for m := range srcs {
		names = append(names, m)
	}
	sort.Strings(names)
	fmt.Println()
	fmt.Println("// originalTeleportMaps are the maps whose doors come from originalTeleports.")
	fmt.Println("var originalTeleportMaps = map[string]bool{")
	for _, m := range names {
		fmt.Printf("\t%q: true,\n", strings.ToLower(m))
	}
	fmt.Println("}")

	var gone []string
	for m, c := range missing {
		gone = append(gone, fmt.Sprintf("%s (%d)", m, c))
	}
	sort.Strings(gone)
	fmt.Fprintf(os.Stderr, "%d doors on %d maps; destinations the port doesn't have: %s\n",
		len(doors), len(names), strings.Join(gone, ", "))
}
