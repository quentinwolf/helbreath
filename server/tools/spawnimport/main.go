// Command spawnimport turns the original server's map spawn rectangles
// (spot-mob-generator lines in MAPDATA/*.txt) into server/internal/game/spawns_gen.go.
//
//	go run ./server/tools/spawnimport -src "<HelbreathServer-main>/Files/GameServers" \
//	    -maps assets/MAPDATA > server/internal/game/spawns_gen.go
//
// Only maps the port has (.amd in -maps) are written. Format of a line:
//
//	spot-mob-generator = <num> <type> <left> <top> <right> <bottom> <mob> <max>
//
// type 1 spawns at random inside the rectangle and wanders there
// (DEF_MOVETYPE_RANDOMAREA); <mob> is the code HGServer's switch turns into an
// NPC.cfg name; <max> is how many are alive at once.
package main

