// oldMobNames: dglv2's spots use the older numbering the random generator still
// uses (4 Zombie, 5 Skeleton...). HGServer's spot switch has no such cases, so
// that server left them empty; we read them the old way so the dungeon has its
// undead and golems. Code 51 is ambiguous (Catapult/Abaddon) and stays skipped.
var oldMobNames = map[int]string{
	4: "Zombie", 5: "Skeleton", 7: "Scorpion", 8: "Stone-Golem", 9: "Cyclops",
}

// typeIDs are our NPC types for names that differ (our guards are all "Guard";
// a few creatures go by another name here).
var typeIDs = map[string]int{
	"Guard-Aresden": 1013, "Guard-Elvine": 1014, "Guard-Neutral": 1015,
	"Orge": 29, "Giant-Frog": 57, "Cannibal-Plant": 60, "Giant-Plant": 76,
}

type spawn struct {
	mapName          string
	num, typeID, max int
	x1, y1, x2, y2   int
	name             string
}

func main() {
	src := flag.String("src", "", "original GameServers folder (searched for MAPDATA/*.txt)")
	mapsDir := flag.String("maps", "assets/MAPDATA", "the port's .amd folder")
	flag.Parse()
	if *src == "" {
		log.Fatal("-src is required")
	}

	// Map names as the port loads them (file name, capitals kept)
	portMaps := map[string]string{}
	entries, err := os.ReadDir(*mapsDir)
	if err != nil {
		log.Fatal(err)
	}
	for _, e := range entries {
		if strings.EqualFold(filepath.Ext(e.Name()), ".amd") {
			name := strings.TrimSuffix(e.Name(), filepath.Ext(e.Name()))
			portMaps[strings.ToLower(name)] = name
		}
	}

	var spawns []spawn
	maxObjects := map[string]int{}
	seen := map[string]string{}
	err = filepath.Walk(*src, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || !strings.EqualFold(filepath.Ext(path), ".txt") ||
			!strings.EqualFold(filepath.Base(filepath.Dir(path)), "mapdata") {
			return err
		}
		key := strings.ToLower(strings.TrimSuffix(filepath.Base(path), filepath.Ext(path)))
		mapName, ok := portMaps[key]
		if !ok {
			return nil
		}
		if first, dup := seen[key]; dup {
			fmt.Fprintf(os.Stderr, "skip duplicate %s (using %s)\n", path, first)
			return nil
		}
		seen[key] = path
		found, maxObj, err := parseMap(path, mapName)
		spawns = append(spawns, found...)
		if maxObj > 0 && len(found) > 0 {
			maxObjects[strings.ToLower(mapName)] = maxObj
		}
		return err
	})
	if err != nil {
		log.Fatal(err)
	}
	sort.SliceStable(spawns, func(i, j int) bool {
		if spawns[i].mapName != spawns[j].mapName {
			return spawns[i].mapName < spawns[j].mapName
		}
		return spawns[i].num < spawns[j].num
	})

	fmt.Println("// Code generated by tools/spawnimport; DO NOT EDIT.")
	fmt.Println("//")
	fmt.Println("// Source: the original server's MAPDATA/*.txt spot-mob-generator lines")
	fmt.Println("// (HelbreathServer-main, HB Server Files 3.51 default maps).")
	fmt.Println()
	fmt.Println("package game")
	fmt.Println()
	fmt.Println("// originalSpotSpawns are the original monster spawn rectangles, by map.")
	fmt.Println("var originalSpotSpawns = []SpawnEntry{")
	maps := map[string]bool{}
	for _, s := range spawns {
		maps[s.mapName] = true
		fmt.Printf("\t{MapName: %q, NpcTypeID: %d, Count: %d, AreaX1: %d, AreaY1: %d, AreaX2: %d, AreaY2: %d}, // %d: %s\n",
			s.mapName, s.typeID, s.max, s.x1, s.y1, s.x2, s.y2, s.num, s.name)
	}
	fmt.Println("}")
	var names []string
	for m := range maps {
		names = append(names, m)
	}
	sort.Strings(names)
	fmt.Println()
	fmt.Println("// originalSpawnMaps are the maps originalSpotSpawns covers.")
	fmt.Println("var originalSpawnMaps = map[string]bool{")
	for _, m := range names {
		fmt.Printf("\t%q: true,\n", strings.ToLower(m))
	}
	fmt.Println("}")
	fmt.Println()
	fmt.Println("// originalMaxObjects are the maps' maximum-object caps: the original stopped")
	fmt.Println("// filling spawn rectangles once this many objects were on the map.")
	fmt.Println("var originalMaxObjects = map[string]int{")
	for _, m := range names {
		if v := maxObjects[strings.ToLower(m)]; v > 0 {
			fmt.Printf("\t%q: %d,\n", strings.ToLower(m), v)
		}
	}
	fmt.Println("}")
	fmt.Fprintf(os.Stderr, "%d spawn rectangles on %d maps\n", len(spawns), len(names))
}

func parseMap(path, mapName string) ([]spawn, int, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, 0, err
	}
	defer f.Close()
	var out []spawn
	maxObj := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if strings.HasPrefix(strings.ToLower(line), "maximum-object") {
			if _, v, ok := strings.Cut(line, "="); ok {
				maxObj, _ = strconv.Atoi(strings.Fields(v + " 0")[0])
			}
			continue
		}
		if !strings.HasPrefix(strings.ToLower(line), "spot-mob-generator") {
			continue
		}
		_, rest, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		f := strings.Fields(strings.Split(rest, "//")[0])
		if len(f) < 8 {
			continue
		}
		v := make([]int, 8)
		for i := range v {
			v[i], _ = strconv.Atoi(f[i])
		}
		num, kind, mob, max := v[0], v[1], v[6], v[7]
		if kind != 1 {
			fmt.Fprintf(os.Stderr, "%s #%d: type %d not supported, skipped\n", mapName, num, kind)
			continue
		}
		name, ok := mobNames[mob]
		if !ok {
			name, ok = oldMobNames[mob]
		}
		if !ok {
			fmt.Fprintf(os.Stderr, "%s #%d: unknown mob code %d, skipped\n", mapName, num, mob)
			continue
		}
		id, ok := typeIDs[name]
		if !ok {
			if t := npc.NpcTypeByName(name); t != nil {
				id = t.ID
			}
		}
		if id == 0 || npc.NpcTypes[id] == nil {
			fmt.Fprintf(os.Stderr, "%s #%d: no NPC type for %s, skipped\n", mapName, num, name)
			continue
		}
		out = append(out, spawn{mapName: mapName, num: num, typeID: id, max: max,
			x1: v[2], y1: v[3], x2: v[4], y2: v[5], name: name})
	}
	return out, maxObj, sc.Err()
}
